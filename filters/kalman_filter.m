function [th, b] = kalman_filter(acc, gx, dt)
% Фільтр Калмана, стан x = [кут; зсув нуля гіроскопа]
persistent x P

% ADJUST: Q - наскільки "довіряємо" гіроскопу, R - шум акселерометра (град^2).
% Більше R - менше шуму, але повільніша корекція (у мене ~3.4 с)
Q = [0.001 0; 0 0.003]*dt;
R = 10;

if isempty(x)
    x = [acc; 0];
    P = eye(2);
end
F = [1 -dt; 0 1];
H = [1 0];

x = F*x + [dt; 0]*gx;          % прогноз за гіроскопом
P = F*P*F' + Q;
G = P*H' / (H*P*H' + R);       % коефіцієнт Калмана
x = x + G*(acc - H*x);         % корекція за акселерометром
P = (eye(2) - G*H)*P;

th = x(1);
b = x(2);
end
