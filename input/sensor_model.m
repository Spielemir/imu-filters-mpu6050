% Модель сигналів датчиків з відомим справжнім кутом
t = (0:dt:60)';
man = t >= 10 & t < 40;                       % маневри з 10 до 40 с
theta = 15*sin(2*pi*0.25*(t-10)) .* man;      % справжній кут, град
w = 15*2*pi*0.25*cos(2*pi*0.25*(t-10)) .* man;
on = t >= 5;                                  % з 5 с працюють двигуни

b = 0.5;        % ADJUST: зсув нуля гіроскопа, град/с (не відкалібрований)
vib = 4*sin(2*pi*17*t) + 2*sin(2*pi*31*t + 1);   % ADJUST: вібрація в акселерометрі

acc = theta + vib .* on;
gx  = w + b + 0.5*sin(2*pi*23*t) .* on;
